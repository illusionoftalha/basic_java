/** Primitive values and String in one runnable example. */
public class JavaDataTypes {
    public static void main(String[] args) {
        int lessons = 3;
        double average = 83.5;
        char initial = 'T';
        boolean learning = true;
        String name = "Talha"; // String is a reference type, not a primitive.
        System.out.println(name + " completed " + lessons + " lessons.");
        System.out.println("Average: " + average);
        System.out.println("Initial: " + initial + "; learning: " + learning);
    }
}
